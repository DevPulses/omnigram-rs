#!/usr/bin/env python3
"""Oracle generator for the storage_serialize crate.

Writes the buffer `ByteArrayWriter` must produce, and the sizes the `*Size()`
helpers must report, from scratch: `struct` for the numbers, UTF-16 big-endian
for strings, and the packed colour / date-time shapes spelled out here.

Run:

    python3 crates/storage_serialize/tests/oracle/gen_oracle.py
"""

import pathlib
import struct

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE.parent / "vectors" / "mod.rs"

NULL_LENGTH = 0xFFFFFFFF

TEXT = "tdata \u041f\u0440\u0438\u0432\u0435\u0442"
BYTE_ARRAY = b"\x00\x01\x02\x03\xfe\xff"
BYTES_VECTOR = b"secret-bytes"
COLOR = (0x12, 0x34, 0x56, 0x78)  # red, green, blue, alpha
JULIAN_DAY = 2460000
MSECS = 45_296_789
SPEC = 0


def i32(value):
    return struct.pack(">i", value)


def u32(value):
    return struct.pack(">I", value)


def u64(value):
    return struct.pack(">Q", value)


def i64(value):
    return struct.pack(">q", value)


def qstring(value):
    units = value.encode("utf-16-be")
    return u32(len(units)) + units


def byte_array(value):
    return u32(len(value)) + value


def bytes_vector(value):
    return u32(NULL_LENGTH) if not value else u32(len(value)) + value


def color(red, green, blue, alpha):
    return u32(red | (green << 8) | (blue << 16) | (alpha << 24))


def date_time(julian_day, msecs, spec):
    return i64(julian_day) + u32(msecs) + struct.pack(">b", spec)


PAYLOAD = b"".join([
    u32(0x01020304),
    i32(-123456),
    u64(0x0102030405060708),
    i64(-1234567890123),
    b"\x01",
    qstring(TEXT),
    u32(NULL_LENGTH),               # null string
    byte_array(BYTE_ARRAY),
    u32(0),                         # empty, non-null byte array
    u32(NULL_LENGTH),               # null byte array
    bytes_vector(BYTES_VECTOR),
    bytes_vector(b""),              # empty bytes vector is null on the wire
    color(*COLOR),
    date_time(JULIAN_DAY, MSECS, SPEC),
])

STRING_SIZE = 4 + len(TEXT.encode("utf-16-be"))
BYTEARRAY_SIZE = 4 + len(BYTE_ARRAY)
BYTES_SIZE = 4 + len(BYTES_VECTOR)

assert STRING_SIZE == 4 + len(TEXT.encode("utf-16-be"))
assert BYTEARRAY_SIZE == 4 + len(BYTE_ARRAY)
assert BYTES_SIZE == 4 + len(BYTES_VECTOR)

# Cut inside the first string's code units.
TRUNCATED = PAYLOAD[: 4 + 4 + 4 + 8 + 8 + 1 + 4 + 3]


def main():
    lines = [
        "// @generated by tests/oracle/gen_oracle.py — do not edit by hand.",
        "//",
        "// Oracle: an independent Python writer of the storage buffer format.",
        "#![allow(dead_code)]",
        "",
        f"pub const TEXT: &str = \"{TEXT}\";",
        f'pub const BYTE_ARRAY_HEX: &str = "{BYTE_ARRAY.hex()}";',
        f'pub const BYTES_VECTOR_HEX: &str = "{BYTES_VECTOR.hex()}";',
        "",
        f"pub const COLOR_PACKED: u32 = {COLOR[0] | (COLOR[1] << 8) | (COLOR[2] << 16) | (COLOR[3] << 24)};",
        f"pub const JULIAN_DAY: i64 = {JULIAN_DAY};",
        f"pub const MSECS: u32 = {MSECS};",
        f"pub const DATE_TIME_SPEC: i8 = {SPEC};",
        "",
        f"pub const STRING_SIZE: usize = {STRING_SIZE};",
        f"pub const BYTEARRAY_SIZE: usize = {BYTEARRAY_SIZE};",
        f"pub const BYTES_SIZE: usize = {BYTES_SIZE};",
        "",
        "/// Every value kind in one buffer, in the order the tests read them.",
        f'pub const PAYLOAD_HEX: &str = "{PAYLOAD.hex()}";',
        "",
        "/// The same buffer cut inside the first string.",
        f'pub const TRUNCATED_HEX: &str = "{TRUNCATED.hex()}";',
        "",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT}")
    print(f"payload {len(PAYLOAD)} bytes")


if __name__ == "__main__":
    main()
