#!/usr/bin/env python3
"""Oracle generator for the mtproto_dc_options crate.

Re-implements `DcOptions::serialize` from scratch — the C++ layout, no code
shared with the Rust port — for the built-in endpoint tables and for a fixture
store that covers every endpoint shape.

Run:

    python3 crates/mtproto_dc_options/tests/oracle/gen_oracle.py
"""

import pathlib
import struct

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE.parent / "vectors" / "mod.rs"

VERSION = 2
STATIC = 1 << 4
IPV6 = 1 << 0
MEDIA_ONLY = 1 << 1
TCPO_ONLY = 1 << 2
CDN = 1 << 3
SECRET = 1 << 10

# The built-in tables, transcribed from `mtproto_dc_options.cpp`.
BUILT_IN = [
    (1, "149.154.175.50", 443),
    (2, "149.154.167.51", 443),
    (2, "95.161.76.100", 443),
    (3, "149.154.175.100", 443),
    (4, "149.154.167.91", 443),
    (5, "149.154.171.5", 443),
]
BUILT_IN_IPV6 = [
    (1, "2001:0b28:f23d:f001:0000:0000:0000:000a", 443),
    (2, "2001:067c:04e8:f002:0000:0000:0000:000a", 443),
    (3, "2001:0b28:f23d:f003:0000:0000:0000:000a", 443),
    (4, "2001:067c:04e8:f004:0000:0000:0000:000a", 443),
    (5, "2001:0b28:f23f:f005:0000:0000:0000:000a", 443),
]
BUILT_IN_TEST = [
    (1, "149.154.175.10", 443),
    (2, "149.154.167.40", 443),
    (3, "149.154.175.117", 443),
]
BUILT_IN_IPV6_TEST = [
    (1, "2001:0b28:f23d:f001:0000:0000:0000:000e", 443),
    (2, "2001:067c:04e8:f002:0000:0000:0000:000e", 443),
    (3, "2001:0b28:f23d:f003:0000:0000:0000:000e", 443),
]


def i32(value):
    return struct.pack(">i", value)


def endpoint_bytes(dc_id, flags, ip, port, secret):
    raw_ip = ip.encode("ascii")
    return (
        i32(dc_id)
        + i32(flags)
        + i32(port)
        + i32(len(raw_ip))
        + raw_ip
        + i32(len(secret))
        + secret
    )


def serialize(endpoints, cdn_keys=()):
    """`DcOptions::serialize` — endpoints sorted per dc, then the CDN section."""
    per_dc = {}
    for dc_id, flags, ip, port, secret in endpoints:
        per_dc.setdefault(dc_id, []).append((flags, ip, port, secret))
    ordered = sorted(per_dc.items())

    out = i32(-VERSION)
    out += i32(sum(len(items) for _, items in ordered))
    for dc_id, items in ordered:
        for flags, ip, port, secret in items:
            out += endpoint_bytes(dc_id, flags, ip, port, secret)
    out += i32(len(cdn_keys))
    for dc_id, n, e in cdn_keys:
        out += i32(dc_id) + i32(len(n)) + n + i32(len(e)) + e
    return out


def built_in_blob(test_mode=False):
    v4 = BUILT_IN_TEST if test_mode else BUILT_IN
    v6 = BUILT_IN_IPV6_TEST if test_mode else BUILT_IN_IPV6
    entries = [(dc, STATIC, ip, port, b"") for dc, ip, port in v4]
    entries += [(dc, STATIC | IPV6, ip, port, b"") for dc, ip, port in v6]
    return serialize(entries)


# A fixture store covering every endpoint shape.
# 21 bytes with the 0xEE head: the shortest obfuscated secret `ValidateSecret` takes.
SECRET_OBFUSCATED = bytes([0xEE]) + bytes(range(1, 21))
FIXTURE_ENDPOINTS = [
    (2, STATIC, "149.154.167.51", 443, b""),
    (2, 0, "95.161.76.100", 443, b""),
    (2, STATIC | IPV6, "2001:067c:04e8:f002::a", 443, bytes(16)),
    (3, STATIC | TCPO_ONLY | SECRET, "149.154.175.100", 443, SECRET_OBFUSCATED),
    (4, STATIC | MEDIA_ONLY, "149.154.167.91", 443, b""),
    (4, STATIC | CDN, "149.154.167.92", 443, b""),
    (5, STATIC, "149.154.171.5", 8443, b""),
]
FIXTURE_CDN_KEYS = [(4, bytes([0x01, 0x02, 0x03]), bytes([0x01, 0x00, 0x01]))]
FIXTURE_BLOB = serialize(FIXTURE_ENDPOINTS, FIXTURE_CDN_KEYS)


def bad_blob(ip_size=None, secret_size=None, truncate=0):
    """A blob the reader must refuse, optionally with a broken field."""
    parts = i32(-VERSION) + i32(1)
    ip = b"1.2.3.4"
    parts += i32(2) + i32(0) + i32(443)
    parts += i32(len(ip) if ip_size is None else ip_size)
    parts += ip
    parts += i32(0 if secret_size is None else secret_size)
    parts += i32(0)
    if truncate:
        parts = parts[:-truncate]
    return parts


def main():
    lines = [
        "// @generated by tests/oracle/gen_oracle.py — do not edit by hand.",
        "//",
        "// Oracle: an independent Python writer of the DcOptions blob format.",
        "#![allow(dead_code)]",
        "",
        "/// Built-in production endpoints, serialized by the oracle.",
        f'pub const BUILT_IN_BLOB_HEX: &str = "{built_in_blob().hex()}";',
        "/// Built-in test endpoints, serialized by the oracle.",
        f'pub const BUILT_IN_TEST_BLOB_HEX: &str = "{built_in_blob(True).hex()}";',
        "",
        "/// A store with every endpoint shape, plus one CDN public key.",
        f'pub const FIXTURE_BLOB_HEX: &str = "{FIXTURE_BLOB.hex()}";',
        f'pub const FIXTURE_SECRET_HEX: &str = "{SECRET_OBFUSCATED.hex()}";',
        "",
        "/// Blobs the reader must refuse.",
        f'pub const BAD_IP_ZERO_HEX: &str = "{bad_blob(ip_size=0).hex()}";',
        f'pub const BAD_IP_LONG_HEX: &str = "{bad_blob(ip_size=46).hex()}";',
        f'pub const BAD_SECRET_LONG_HEX: &str = "{bad_blob(secret_size=33).hex()}";',
        f'pub const TRUNCATED_HEX: &str = "{bad_blob(truncate=3).hex()}";',
        "",
        "/// A version-0 blob: the first field is the count, no secret section.",
        f'pub const VERSION_ZERO_BLOB_HEX: &str = "{(i32(1) + i32(2) + i32(0) + i32(443) + i32(7) + b"1.2.3.4").hex()}";',
        "",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT}")
    print(f"built-in blob {len(built_in_blob())} bytes, fixture {len(FIXTURE_BLOB)} bytes")


if __name__ == "__main__":
    main()